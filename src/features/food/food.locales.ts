export function getFoodCopy(food: Food, locale: Locale) {
  if (locale === 'en') return { name: food.name, description: food.description, ingredients: food.ingredients, tags: food.tags }
  const translated = vi[food.id]
  return {
    name: translated?.name ?? food.name,
    description: translated?.description ?? food.description,
    ingredients: food.ingredients.map((item) => ingredientsVi[item] ?? item),
    tags: food.tags.map((item) => tagsVi[item] ?? item),
  }
}
